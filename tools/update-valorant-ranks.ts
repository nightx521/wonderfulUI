import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { compiledValorantAssetPath } from './valorant-asset-config.ts';
import { publishValorantMetadataTransaction } from './valorant-metadata-transaction.ts';

// Explicitly pin the current standard tier scheme, which includes Ascendant.
const TIER_SET = '03621f52-342b-cf4e-4f86-9350a49c6d04';
const ENDPOINT = `https://valorant-api.com/v1/competitivetiers/${TIER_SET}?language=zh-CN`;
const MEDIA_ORIGIN = 'https://media.valorant-api.com';
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const response = await fetch(ENDPOINT, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`Tier metadata HTTP ${response.status}`);
const payload = await response.json() as { data?: { tiers?: Array<{ tier: number; tierName: string; largeIcon: string | null }> } };
if (!Array.isArray(payload.data?.tiers)) throw new Error('Missing competitive tiers');
const ranks = payload.data.tiers.filter(record => record.tier === 0 || record.tier >= 3 && record.tier <= 27)
  .map(record => {
    if (!Number.isInteger(record.tier) || !record.tierName?.trim() || !record.largeIcon) throw new Error('Invalid tier record');
    const url = new URL(record.largeIcon);
    if (url.protocol !== 'https:' || url.origin !== MEDIA_ORIGIN) throw new Error('Invalid rank image origin');
    return { uuid: String(record.tier), tier: record.tier, cn: record.tierName.trim(), sourceImage: url.href };
  }).sort((a, b) => a.tier - b.tier);
if (ranks.length !== 26 || new Set(ranks.map(record => record.tier)).size !== 26) throw new Error('Incomplete standard rank scheme');

await publishValorantMetadataTransaction({
  sourceRoot: join(repoRoot, 'packages/gui/assets/valorant-source'),
  metadataFile: join(repoRoot, 'packages/gui/src/utils/generated/valorant-ranks.zh-CN.ts'),
  groups: [{ kind: 'ranks', records: ranks }],
  concurrency: 4,
  async download(url) {
    const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    if (!res.ok) throw new Error(`Rank image HTTP ${res.status}`);
    if (Number(res.headers.get('content-length') ?? 0) > 4 * 1024 * 1024) throw new Error('Rank image exceeds size limit');
    const bytes = new Uint8Array(await res.arrayBuffer());
    if (!bytes.length || bytes.length > 4 * 1024 * 1024) throw new Error('Invalid rank image size');
    const meta = await sharp(bytes, { failOn: 'error' }).metadata();
    if (meta.format !== 'png' || !meta.width || !meta.height || meta.width < 128 || meta.height < 128
      || meta.width > 1024 || meta.height > 1024 || meta.width / meta.height < 0.5 || meta.width / meta.height > 2)
      throw new Error(`Invalid rank PNG: ${url} (${meta.format}, ${meta.width}x${meta.height})`);
    return { bytes, hash: createHash('sha256').update(bytes).digest('hex') };
  },
  renderMetadata(hashes) {
    const records = ranks.map(({ tier, cn, uuid }) => {
      const sourceSha256 = hashes.get('ranks')!.get(uuid)!;
      return { tier, cn, image: compiledValorantAssetPath('ranks', sourceSha256), sourceSha256 };
    });
    return `// Generated by tools/update-valorant-ranks.ts. Do not hand-edit.
// Source: ${ENDPOINT}
// Source media origin: ${MEDIA_ORIGIN}
// Tier scheme: ${TIER_SET}
export interface ValorantRankMetadata {
  tier: number;
  cn: string;
  image: string;
  sourceSha256: string;
}

export const VALORANT_RANKS: readonly ValorantRankMetadata[] = ${JSON.stringify(records, null, 2)};
`;
  },
});
console.log(`Published ${ranks.length} competitive rank icons and metadata`);
